/**
 * 시연 기준일 — 이 화면의 **모든 칸이 같은 날을 본다**.
 *
 * ★ 20 = 2024-08-30(금). 시연 날짜(8월 31일)에 맞추려 했으나 **8/31 은 토요일이라 이
 *   데이터(영업일 61일)에 없다.** 8월의 마지막 영업일이 30일이라 그날로 잡았다.
 * ⚠️ 이 값은 **날짜가 아니라 영업일 번호**다. 20 은 "20일"이 아니다 — `REAL_DATES[20]` 이
 *    실제 날짜다. 숫자만 보고 날짜로 읽으면 안 된다.
 * ⚠️ 예전에는 지도만 420ms 마다 날짜를 넘기고(0→60 무한 반복) 나머지 두 칸은 29 에
 *    못 박혀 있어서, 같은 화면에서 A구역이 1429/2288 과 2027/2288 로 **동시에** 보였다
 *    (사용자 지적). 세 칸이 한 상수를 보게 해서 그 어긋남을 없앤다.
 */
export const DEMO_DAY = 20;

export function gradeStats(day) {
  const layout = computeLayout();
  return layout.zones.map((z) => {
    const occ = Math.min(0.99, Math.max(0.015,
      (REAL_INV[z.g.invKey][day] / INV_PEAK[z.g.invKey]) * 0.95));
    const total = z.racks.length * z.g.levels * z.g.cols;
    return { g: z.g, occ, total, filled: Math.round(occ * total) };
  }).sort((a, b) => (a.g.code < b.g.code ? -1 : 1));
}
